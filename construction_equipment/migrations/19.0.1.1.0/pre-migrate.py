def _move_xmlids(cr, source, target, xmlids):
    moved = 0
    for model, names in xmlids.items():
        cr.execute("""
            UPDATE ir_model_data d
               SET module = %s
             WHERE d.module = %s
               AND d.model = %s
               AND d.name IN %s
               AND NOT EXISTS (SELECT 1 FROM ir_model_data o WHERE o.module = %s AND o.name = d.name)
        """, [target, source, model, tuple(names), target])
        moved += cr.rowcount
    return moved


def _mark_to_install(cr, module):
    cr.execute("SELECT state FROM ir_module_module WHERE name = %s", [module])
    row = cr.fetchone()
    if not row:
        _logger.warning("Module %s is not in the apps list: install it to recover its data", module)
    elif row[0] in ('uninstalled', 'to remove'):
        cr.execute("UPDATE ir_module_module SET state = 'to install' WHERE name = %s", [module])


def migrate(cr, version):
    if not version:
        return
    moved = _move_xmlids(cr, 'construction_equipment', 'construction_fleet', FLEET_XMLIDS)
    _mark_to_install(cr, 'construction_fleet')
    _logger.info("Construction Machines & Equipment: %s records moved to construction_fleet", moved)
